package unit

import (
	"os"
	"path/filepath"
	"strings"
	"testing"

	"omnia/internal/mime"
)

func TestDetectMime(t *testing.T) {
	tempDir := t.TempDir()

	// 1. Text File
	txtPath := filepath.Join(tempDir, "sample.txt")
	_ = os.WriteFile(txtPath, []byte("Hello world test file"), 0644)

	mimeType, err := mime.DetectMime(txtPath)
	if err != nil {
		t.Fatalf("unexpected error detecting text mime: %v", err)
	}
	if !strings.HasPrefix(mimeType, "text/plain") {
		t.Errorf("expected text/plain, got %s", mimeType)
	}

	// 2. PNG Image File (Magic Bytes)
	pngPath := filepath.Join(tempDir, "sample.png")
	pngBytes := []byte{
		0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a, 0x00, 0x00, 0x00, 0x0d,
		0x49, 0x48, 0x44, 0x52, 0x00, 0x00, 0x00, 0x01, 0x00, 0x00, 0x00, 0x01,
		0x08, 0x02, 0x00, 0x00, 0x00, 0x90, 0x77, 0x53, 0xde, 0x00, 0x00, 0x00,
		0x0c, 0x49, 0x44, 0x41, 0x54, 0x08, 0xd7, 0x63, 0xf8, 0xcf, 0xc0, 0x00,
		0x00, 0x03, 0x01, 0x01, 0x00, 0x18, 0xdd, 0x8d, 0xb0, 0x00, 0x00, 0x00,
		0x00, 0x49, 0x45, 0x4e, 0x44, 0xae, 0x42, 0x60, 0x82,
	}
	_ = os.WriteFile(pngPath, pngBytes, 0644)

	mimeType, err = mime.DetectMime(pngPath)
	if err != nil {
		t.Fatalf("unexpected error detecting png mime: %v", err)
	}
	if mimeType != "image/png" {
		t.Errorf("expected image/png, got %s", mimeType)
	}
}
